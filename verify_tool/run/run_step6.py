def log(tag, msg):
    print(f"[{tag}] {msg}", flush=True)


def _place_file(p, dry_run):
    """Copy a source into the destination Step 6 expects. For the Cluster
    blended_model, also split its KEY column into Cluster + ItemCode, because our
    growing output_summary carries only KEY ('Clinics 0-AAP115') while Step 6's
    read_blended_model_data expects an ItemCode column to rename to ProductKey
    (BCG's facit had it pre-split; our raw model output does not). This adaptation
    lives in the runner so Fall_Back_Logic.py stays untouched.
    Split on the LAST '-' (rsplit) -- cluster names contain spaces but no hyphens,
    ItemCodes contain no hyphens; matches rationality helper's extract_cluster_from_key.
    """
    import pandas as pd

    if dry_run:
        return

    p["dest"].parent.mkdir(parents=True, exist_ok=True)

    if p.get("split_key"):
        df = pd.read_excel(p["src"])
        if "KEY" in df.columns and "ItemCode" not in df.columns:
            parts = df["KEY"].astype(str).str.rsplit("-", n=1)
            df["Cluster"] = parts.str[0]
            df["ItemCode"] = parts.str[1]
            log("   ", f"     split KEY -> Cluster + ItemCode ({len(df):,} rows)")
        df.to_excel(p["dest"], index=False, engine="openpyxl")
    else:
        shutil.copy2(p["src"], p["dest"])


