def preflight(dry_run: bool) -> bool:
    log("PREFLIGHT", "checking Step 6 inputs ...")
    ok = True

    for a in ALREADY:
        if a["path"].exists():
            log("OK", f"{a['label']:<34} [{a['kind']}] in place")
        else:
            log("MISSING", f"{a['label']:<34} expected at {a['path']}")
            ok = False

    for p in PLACEMENTS:
        if not p["src"].exists():
            log("MISSING-SRC", f"{p['label']:<34} source not found: {p['src']}")
            ok = False
            continue
        action = "would place" if dry_run else "placing"
        log("PLACE", f"{p['label']:<34} [{p['kind']}] {action}")
        log("   ", f"     from: {p['src']}")
        log("   ", f"     to:   {p['dest']}")
        _place_file(p, dry_run)

    if not ok:
        log("ABORT", "one or more inputs/sources missing -- Step 6 cannot run")
    return ok


def run_step6() -> int:
    script = FBL / "Fall_Back_Logic.py"
    if not script.exists():
        log("ERROR", f"Fall_Back_Logic.py not found at {script}")
        return 1
    log("RUN", f"executing {script.name} (cwd={FBL}) ...")
    # chdir into the Step 6 folder so Constant.py's relative paths resolve.
    proc = subprocess.run(
        [sys.executable, str(script)],
        cwd=str(FBL),
        capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=1800,
    )
    if proc.stdout:
        print(proc.stdout.rstrip())
    if proc.returncode != 0:
        # Known-benign case (LB.53): Final_Fallback_Data is written (rows 671/686)
        # BEFORE the cosmetic template/named-range write (row 691) that throws a
        # COM error when the Sweden_Fallback.xlsx template lacks the 'raw' name.
        # If the data file exists, the run SUCCEEDED on the part that matters.
        is_template_comerror = (
            "write_df_preserve_named_range" in (proc.stderr or "")
            or "com_error" in (proc.stderr or "").lower()
            or "wb.names" in (proc.stderr or "")
        )
        data_written = bool(
            list((FBL / "output_data").glob("Final_Fallback_Data*.xlsx"))
            or list(FBL.glob("Final_Fallback_Data*.xlsx"))
        )
        if is_template_comerror and data_written:
            log("RUN-WARN", "Fall_Back_Logic.py threw on the COSMETIC template write "
                            "(LB.53: Sweden_Fallback.xlsx named-range). The fallback DATA "
                            "was written before that step -- treating run as SUCCESS.")
            log("RUN-WARN", "Dashboard template NOT refreshed. To fix permanently, add the "
                            "'raw' named range to the template, or wrap the write in "
                            "try/wb.names.add. Data is unaffected.")
            return 0
        log("RUN-FAIL", f"exit {proc.returncode}")
        if proc.stderr:
            print("---- STDERR ----")
            print(proc.stderr.rstrip())
        return proc.returncode
    log("RUN-OK", "Fall_Back_Logic.py completed")
    return 0


def verify_output() -> int:
    """R7: trust the file, not the log. Find newest Final_Fallback_Data*.xlsx,
    report rows + elasticity_level (F1-F7) distribution = the FD.11 trigger signal."""
    import pandas as pd

    # Step 6 writes to output_path (.\output_data) and CWD; check both.
    candidates = list((FBL / "output_data").glob("Final_Fallback_Data*.xlsx")) + \
                 list(FBL.glob("Final_Fallback_Data*.xlsx"))
    if not candidates:
        log("VERIFY-FAIL", "no Final_Fallback_Data*.xlsx produced")
        return 1
    newest = max(candidates, key=lambda p: p.stat().st_mtime)
    log("VERIFY", f"newest output: {newest.name} ({newest.stat().st_size/1e6:.1f} MB)")

    df = pd.read_excel(newest)
    log("ROWS", f"{len(df):,} rows, {df['ProductKey'].nunique():,} distinct ProductKeys"
                 if "ProductKey" in df.columns else f"{len(df):,} rows")

    if "elasticity_level" in df.columns:
        log("F-LEVELS", "elasticity source distribution (the FD.11 bundle-trigger signal):")
        vc = df["elasticity_level"].value_counts(dropna=False)
        total = len(df)
        for lvl, n in vc.items():
            marker = "  <-- BUNDLE" if isinstance(lvl, str) and ("F2" in lvl or "F4" in lvl) else ""
            print(f"           {str(lvl):<32} {n:>8,}  ({100*n/total:5.1f}%){marker}")
        bundle_rows = df["elasticity_level"].astype(str).str.contains("F2|F4").sum()
        log("BUNDLE-WIN", f"F2/F4 (bundle) chosen for {bundle_rows:,} rows "
                          f"({100*bundle_rows/total:.1f}%) -- FD.11 revisit signal")
        if bundle_rows == 0:
            log("READ", "bundle NEVER wins -> parking is safe; bundle adds nothing the weave needs.")
        elif 100*bundle_rows/total < 3:
            log("READ", "bundle wins rarely (<3%) -> parking low-risk; revisit only if those KEYs matter.")
        else:
            log("READ", "bundle wins materially -> FD.11 revisit warranted; bundle rescues real KEYs.")

    if "final_elasticity" in df.columns:
        fe = pd.to_numeric(df["final_elasticity"], errors="coerce")
        log("ELAST", f"final_elasticity: median {fe.median():.3f}, "
                     f"negative {100*(fe<0).mean():.1f}%, "
                     f"in (-10,0) {100*((fe>-10)&(fe<0)).mean():.1f}%")
    return 0


